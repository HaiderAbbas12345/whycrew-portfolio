/**
 * Renders one or more schema.org objects as JSON-LD. Server-rendered, so the
 * markup is in the initial HTML where crawlers that don't run JavaScript can
 * still read it.
 */
export function JsonLd({ data }: { data: object | object[] }) {
  const blocks = Array.isArray(data) ? data : [data];
  return (
    <>
      {blocks.map((block, i) => (
        <script
          key={i}
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: JSON.stringify(block) }}
        />
      ))}
    </>
  );
}
